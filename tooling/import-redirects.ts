import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createDb } from './db-bridge.ts';
import { redirect as redirectTable } from '../packages/db/src/schema.ts';
import { sql } from 'drizzle-orm';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const CLASSIFICATION_FILE = resolve(HERE, 'data/legacy_url_classification.json');
const NGINX_MAP_FILE = resolve(ROOT, 'deploy/nginx/twinmos-redirects.map');

interface ClassificationEntry {
  from: string;
  to: string;
  code: number;
  category: string;
  source: string;
  reason: string;
}

async function main() {
  console.log('================================================================');
  console.log('  TwinMOS URL Migration Importer: T6.4.1 & T6.4.2');
  console.log('================================================================\n');

  const raw = readFileSync(CLASSIFICATION_FILE, 'utf8');
  const entries: ClassificationEntry[] = JSON.parse(raw);
  console.log(`Loaded ${entries.length} classification entries.`);

  const db = createDb();

  // Filter entries that belong in redirect table (301 and 410)
  const redirectRows = entries.filter((e) => (e.code === 301 || e.code === 410) && e.from !== e.to);
  console.log(`Found ${redirectRows.length} redirect/gone rules to import into 'redirect' table.`);

  let inserted = 0;
  let updated = 0;

  for (const row of redirectRows) {
    try {
      await db
        .insert(redirectTable)
        .values({
          from: row.from,
          to: row.to,
          code: row.code,
        })
        .onConflictDoUpdate({
          target: redirectTable.from,
          set: {
            to: row.to,
            code: row.code,
          },
        });
      inserted++;
    } catch (err: any) {
      console.error(`Failed to insert redirect: ${row.from} -> ${row.to}`, err.message);
    }
  }

  console.log(`\nDatabase import complete: ${inserted} rows upserted into 'redirect' table.`);

  // Verify database count
  const allInDb = await db.select().from(redirectTable);
  console.log(`Total rows in 'redirect' table: ${allInDb.length}`);

  // Synchronize deploy/nginx/twinmos-redirects.map for 301 redirects
  const nginx301Rows = redirectRows.filter((r) => r.code === 301);
  const nginxLines = [
    '# TwinMOS legacy URL -> current URL map (NGINX map include, NF-14 / R-08 / MS6.4)',
    '# Auto-generated by tooling/import-redirects.ts from master classification',
    '# Total rules: ' + nginx301Rows.length,
    '',
  ];

  for (const r of nginx301Rows) {
    nginxLines.push(`${r.from} ${r.to};`);
  }

  writeFileSync(NGINX_MAP_FILE, nginxLines.join('\n') + '\n', 'utf8');
  console.log(`Successfully synced ${nginx301Rows.length} 301 redirect rules to ${NGINX_MAP_FILE}`);

  console.log('\n✅ Task T6.4.1 & T6.4.2 database import and NGINX map synchronization complete.');
  process.exit(0);
}

main().catch((err) => {
  console.error('[import-redirects] Fatal error:', err);
  process.exit(1);
});
